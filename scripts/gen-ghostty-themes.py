#!/usr/bin/env python3
"""Generate ghostty themes and fonts from the kitty theme and font files.

Same idea as gen-nvim-themes.py: kitty is the single source of truth, so ghostty
colours and fonts are derived rather than declared again.
"""

import glob
import os
import re

KITTY = os.path.expanduser("~/.dotfiles/.config/kitty")
DST = os.path.expanduser("~/.dotfiles/.config/ghostty")
os.makedirs(f"{DST}/themes", exist_ok=True)
os.makedirs(f"{DST}/fonts", exist_ok=True)

# kitty key -> ghostty key
KEYS = {
    "background": "background",
    "foreground": "foreground",
    "background_opacity": "background-opacity",
    "background_blur": "background-blur",
    "selection_background": "selection-background",
    "selection_foreground": "selection-foreground",
    "cursor": "cursor-color",
    "cursor_text_color": "cursor-text",
}


def parse(path):
    p = {}
    for line in open(path, encoding="utf-8"):  # noqa: SIM115
        m = re.match(r"^(\w+)\s+(#[0-9a-fA-F]{6}|[0-9.]+)\s*$", line)
        if m:
            p[m.group(1)] = m.group(2).lower()
    return p


for src in sorted(glob.glob(f"{KITTY}/themes/*.conf")):
    name = os.path.basename(src)[:-5]
    p = parse(src)
    with open(f"{DST}/themes/{name}", "w") as f:
        f.write(f"# {name} — generated by scripts/gen-ghostty-themes.py from the kitty theme.\n")
        f.write("# Copied to ~/.config/ghostty/current-theme by `set-theme`.\n")
        for k, g in KEYS.items():
            if k in p:
                f.write(f"{g} = {p[k]}\n")
        for i in range(16):
            f.write(f"palette = {i}={p[f'color{i}']}\n")
    print(f"  {name}")

# kitty matches this name loosely; the installed family has the Mono suffix
FAMILY = {"jetbrains-mono": "JetBrainsMono Nerd Font Mono"}

# ghostty finds the bold and italic faces itself, so only the family is needed.
# kitty names a face ("VictorMono Nerd Font Mono Regular"); ghostty wants the family.
for src in sorted(glob.glob(f"{KITTY}/fonts/*.conf")):
    name = os.path.basename(src)[:-5]
    family = None
    for line in open(src, encoding="utf-8"):  # noqa: SIM115
        m = re.match(r"^font_family\s+(.+?)(?:\s+Regular)?\s*$", line)
        if m:
            family = m.group(1)
    family = FAMILY.get(name, family)
    with open(f"{DST}/fonts/{name}", "w") as f:
        f.write(f"# {name} — generated by scripts/gen-ghostty-themes.py from the kitty font.\n")
        f.write("# Copied to ~/.config/ghostty/current-font by `set-font`.\n")
        f.write(f'font-family = "{family}"\n')
    print(f"  {name}")
print("done")
